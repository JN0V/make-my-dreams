// lib/readme-sync/build-status-block.js — pure builder for README.md's
// mechanical "Status" block (SPEC_V03D AC-2).
//
// SRP (universal.md §I.S): derive the one mechanical Status block of README.md
// from deterministic, cheap sources and return it as markdown. It is the README
// counterpart of lib/handover/build-state-block.js and REUSES that module's
// helpers (gitField / unavailable / renderAdrCount) rather than duplicating them
// (SPEC_V03D §3 — "extract/share rather than duplicate"). Every dependency
// (git runner, file reader, ADR lister, lessons parser) is INJECTED, so the
// builder is pure: same inputs → same markdown, and the AC-2 unit test drives it
// with fakes that never touch real git/fs.
//
// Honesty (universal.md §VI, ai-coding.md §I): a failing git call, a missing
// tag, or an unreadable package.json renders an explicit `(unavailable: <reason>)`
// value — NEVER a crash, NEVER a guess, NEVER a stale copy. The one non-cheap
// field (the passing-test count) is supplied via `--tests N` or left as an
// explicit "run npm test" placeholder; the builder never invents it (AC-2).

import { gitField, unavailable, renderAdrCount } from '../handover/build-state-block.js';

/**
 * Count active lessons via the authoritative parser (never a hand-tally).
 * @returns {string} e.g. "22 active" or "(unavailable: …)"
 */
function renderLessonCount(readFile, parseLessons, lessonsPath) {
  try {
    const parsed = parseLessons(readFile(lessonsPath));
    const active = parsed.filter((l) => l.status === 'active').length;
    return `${active} active`;
  } catch (err) {
    return unavailable(`lessons-learned.md: ${err.message}`);
  }
}

/**
 * Build the mechanical README Status block markdown.
 *
 * @param {{
 *   runGit: (args: string[], cwd: string) => Promise<object>,
 *   repoRoot: string,
 *   readFile: (absPath: string) => string,        // sync reader; throws on missing
 *   parseLessons: (markdown: string) => Array<{ id: string, status: string }>,
 *   listAdrFiles: () => string[],                  // ADR *.md filenames
 *   paths: { packageJson: string, lessons: string },
 *   tests?: number|null,                           // from --tests N (honest count)
 * }} opts
 * @returns {Promise<string>} the markdown block (no surrounding markers/newlines)
 */
export async function buildStatusBlock(opts) {
  const {
    runGit,
    repoRoot,
    readFile,
    parseLessons,
    listAdrFiles,
    paths,
    tests = null,
  } = opts || {};

  // ── version (package.json) ──────────────────────────────────────────────────
  let version;
  try {
    version = `\`${JSON.parse(readFile(paths.packageJson)).version}\` (package.json)`;
  } catch (err) {
    version = unavailable(`package.json: ${err.message}`);
  }

  // ── latest tag (git) ────────────────────────────────────────────────────────
  const tagField = await gitField(runGit, ['describe', '--tags', '--abbrev=0'], repoRoot);
  const tag = tagField.ok && tagField.value.length > 0
    ? `\`${tagField.value}\``
    : unavailable(tagField.ok ? 'no tags found' : tagField.reason);

  // ── ADR count ───────────────────────────────────────────────────────────────
  let adrs;
  try {
    adrs = renderAdrCount(listAdrFiles());
  } catch (err) {
    adrs = unavailable(`adr dir: ${err.message}`);
  }

  // ── active lessons (parseLessons — authoritative) ───────────────────────────
  const lessons = renderLessonCount(readFile, parseLessons, paths.lessons);

  // ── reflexive-slice count = number of release tags (AC-2). Each MMD slice
  //    ships under a `v0.*` release tag, so the release-tag count is the honest
  //    mechanical proxy for "reflexive --here slices". A failing git call →
  //    (unavailable: …), never a fabricated number.
  const relTagsField = await gitField(runGit, ['tag', '--list', 'v*'], repoRoot);
  const reflexiveSlices = relTagsField.ok
    ? String(relTagsField.value.split('\n').filter((l) => l.trim().length > 0).length)
    : unavailable(relTagsField.reason);

  // ── test count (honest — never invented; AC-2) ─────────────────────────────
  const testsLine = Number.isInteger(tests) && tests >= 0
    ? `${tests} passing`
    : '(run `npm test` to refresh — pass `mmdream document --tests N`)';

  // ── assemble the block ──────────────────────────────────────────────────────
  const lines = [
    `- **Version**: ${version}`,
    `- **Latest tag**: ${tag}`,
    `- **ADRs**: ${adrs}`,
    `- **Active lessons**: ${lessons}`,
    `- **Reflexive slices (release tags)**: ${reflexiveSlices}`,
    `- **Tests**: ${testsLine}`,
    '- _Mechanical block — regenerated by `mmdream document`; the prose History and command docs are human-authored._',
  ];

  return lines.join('\n');
}
